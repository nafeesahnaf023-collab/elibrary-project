/* Athenaeum — file store (IndexedDB) + delivery of book files.
   Real backend: replace FileStore with cloud storage (signed URLs). */
const FileStore = {
  _open(){
    return new Promise((res, rej) => {
      if(!window.indexedDB) return rej(new Error('IndexedDB unavailable'));
      const r = indexedDB.open('athenaeum_files', 1);
      r.onupgradeneeded = () => r.result.createObjectStore('files');
      r.onsuccess = () => res(r.result);
      r.onerror = () => rej(r.error);
    });
  },
  async _tx(mode, fn){
    const db = await this._open();
    return new Promise((res, rej) => {
      const req = fn(db.transaction('files', mode).objectStore('files'));
      req.onsuccess = () => res(req.result);
      req.onerror = () => rej(req.error);
    });
  },
  async put(id, blob){
    if(SB.enabled) await SB.filePut(id, blob);            // remote first: if it fails the upload reports an error
    return this._tx('readwrite', s => s.put(blob, id)).catch(e => { if(!SB.enabled) throw e; });
  },
  async get(id){
    const local = await this._tx('readonly', s => s.get(id)).catch(() => null);
    if(local || !SB.enabled) return local;
    const remote = await SB.fileGet(id).catch(() => null);
    if(remote) this._tx('readwrite', s => s.put(remote, id)).catch(() => {});
    return remote;
  },
  async del(id){
    if(SB.enabled) await SB.fileDel(id).catch(() => {});
    return this._tx('readwrite', s => s.delete(id)).catch(() => {});
  },
};

/* Valid single-page PDF used for sample catalogue books that have no uploaded file */
function makeSamplePDF(book){
  const clean = t => String(t || '').replace(/[^\x20-\x7E]/g, '?').replace(/([()\\])/g, '\\$1');
  const wrap = (t, n) => {
    const lines = []; let l = '';
    clean(t).split(' ').forEach(w => { if((l + ' ' + w).length > n && l){ lines.push(l); l = w; } else l = l ? l + ' ' + w : w; });
    if(l) lines.push(l);
    return lines;
  };
  let stream = 'BT /F1 22 Tf 28 TL 60 770 Td ' + wrap(book.title, 38).map(l => `(${l}) Tj T*`).join(' ') + ' ET\n';
  stream += `BT /F1 13 Tf 18 TL 60 ${770 - 28 * wrap(book.title, 38).length - 20} Td (by ${clean(book.author)}) Tj T* (${clean(book.university)}) Tj T* T* `
    + wrap(book.description, 80).map(l => `(${l}) Tj T*`).join(' ') + ' T* (Sample document generated by Athenaeum.) Tj ET';
  const objs = [null,
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
    `<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`];
  let pdf = '%PDF-1.4\n'; const off = [];
  for(let i = 1; i <= 5; i++){ off[i] = pdf.length; pdf += `${i} 0 obj\n${objs[i]}\nendobj\n`; }
  const x = pdf.length;
  pdf += 'xref\n0 6\n0000000000 65535 f \n' + off.slice(1).map(o => String(o).padStart(10, '0') + ' 00000 n \n').join('')
    + `trailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n${x}\n%%EOF`;
  return new Blob([pdf], { type: 'application/pdf' });
}

/* -> { blob, filename } or null when the file is missing */
async function getBookFile(book){
  let blob = await FileStore.get(book.id).catch(() => null);
  if(!blob){
    if(book.hasFile) return null;            // uploaded file is gone -> real error
    blob = makeSamplePDF(book);              // sample catalogue entry
  }
  const isEpub = blob.type === 'application/epub+zip';
  const base = String(book.title || 'book').replace(/[\\/:*?"<>|]+/g, ' ').replace(/\s+/g, ' ').trim().slice(0, 80) || 'book';
  return { blob, isEpub, filename: base + (isEpub ? '.epub' : '.pdf') };
}

/* Read online (PDF opens in a tab; EPUB can't render in a browser so it downloads). Returns true on success. */
async function openBookFile(book){
  if(typeof book === 'string') book = findBookData(book);
  if(!book){ showToast('This book could not be found.'); return false; }
  const win = window.open('', '_blank');
  const f = await getBookFile(book).catch(() => null);
  if(!f){ if(win) win.close(); showToast('Sorry, this book file is unavailable right now.'); return false; }
  if(f.isEpub){ if(win) win.close(); return saveBlob(f); }
  if(!win){ showToast('Your browser blocked the new tab. Allow pop-ups and try again.'); return false; }
  win.location.href = URL.createObjectURL(f.blob);
  return true;
}
function saveBlob(f){
  const a = document.createElement('a');
  a.href = URL.createObjectURL(f.blob); a.download = f.filename;
  document.body.appendChild(a); a.click(); a.remove();
  setTimeout(() => URL.revokeObjectURL(a.href), 10000);
  return true;
}
async function downloadBookFile(book){
  if(typeof book === 'string') book = findBookData(book);
  if(!book){ showToast('This book could not be found.'); return false; }
  const f = await getBookFile(book).catch(() => null);
  if(!f){ showToast('Sorry, this book file is unavailable right now.'); return false; }
  return saveBlob(f);
}

/* Count a download once per reader per book. Returns the updated book (or null if not counted). */
function registerDownload(bookId){
  const key = userKey('el_downloaded'), done = readJSON(key, []);
  if(done.includes(bookId)) return null;
  const all = getBooks(), b = all.find(x => x.id === bookId);
  if(!b) return null;
  done.push(bookId); localStorage.setItem(key, JSON.stringify(done));
  b.downloads = (b.downloads || 0) + 1; saveBooks(all);
  return b;
}
